export function splitPlanText(
  language: SplitPlanLanguage,
  key: string,
  args: Record<string, unknown> = {},
): string {
  const template = (language === "en-US" ? enUS : zhCN)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    String(args[name] ?? `{${name}}`),
  );
}
